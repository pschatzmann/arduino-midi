#include "MidiParser.h"
#include "MidiLogger.h"
#include "TestHelper.h"

using namespace midi;

static void testSingleMessage() {
  RecordingAction action;
  MidiParser parser(&action);
  // header, timestamp, note on
  uint8_t msg[] = {0x80, 0x81, 0x90, 60, 100};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100"}));
}

static void testMultipleMessages() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80, 0x81, 0x90, 60, 100, 0x82, 0xB1, 64, 127};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100", "cc 1 64 127"}));
}

static void testRunningStatusWithTimestamp() {
  RecordingAction action;
  MidiParser parser(&action);
  // the timestamp 0x9A must not be interpreted as note on for channel 10
  uint8_t msg[] = {0x80, 0x81, 0x90, 60, 100, 0x9A, 62, 90};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100", "on 0 62 90"}));
}

static void testRunningStatusWithoutTimestamp() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80, 0x81, 0x90, 60, 100, 62, 90};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100", "on 0 62 90"}));
}

static void testRealtime() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80, 0x81, 0xF8, 0x82, 0xC0, 5};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"pc 0 5"}));
}

static void testPitchBend() {
  RecordingAction14 action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80, 0x81, 0xE0, 0x00, 0x40};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"pb14 0 8192"}));
}

static void testSysexOverMultiplePackets() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg1[] = {0x80, 0x81, 0xF0, 0x01, 0x02};
  uint8_t msg2[] = {0x80, 0x03, 0x04, 0x82, 0xF7, 0x83, 0x90, 60, 100};
  parser.parseBle(msg1, sizeof(msg1));
  parser.parseBle(msg2, sizeof(msg2));
  CHECK(action.take() == Events({"on 0 60 100"}));
}

static void testInvalidPacket() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x00, 0x90, 60, 100};  // header without high bit
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take().empty());
}

static void testShortPackets() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80};
  parser.parseBle(msg, 0);
  parser.parseBle(msg, 1);  // header only
  parser.parseBle(nullptr, 0);
  CHECK(action.take().empty());
}

static void testOneDataByteRunningStatus() {
  RecordingAction action;
  MidiParser parser(&action);
  // running status without and with timestamp
  uint8_t msg[] = {0x80, 0x81, 0xC0, 5, 6, 0x82, 7};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"pc 0 5", "pc 0 6", "pc 0 7"}));
}

static void testSysexInOnePacket() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80, 0x81, 0xF0, 1, 2, 0x82, 0xF7, 0x83, 0x90, 60, 100};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100"}));
}

static void testRealtimeInsideRunningStatus() {
  RecordingAction action;
  MidiParser parser(&action);
  // a realtime message (with its timestamp) must keep the running status
  uint8_t msg[] = {0x80, 0x81, 0x90, 60, 100, 0x82, 0xF8, 0x83, 61, 90};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100", "on 0 61 90"}));
}

static void testTrailingTimestamp() {
  RecordingAction action;
  MidiParser parser(&action);
  uint8_t msg[] = {0x80, 0x81, 0x90, 60, 100, 0x82};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 0 60 100"}));
}

static void testChannelFilter() {
  RecordingAction action;
  MidiParser parser(&action, 2);
  uint8_t msg[] = {0x80, 0x81, 0x91, 60, 100, 0x82, 0x92, 61, 100};
  parser.parseBle(msg, sizeof(msg));
  CHECK(action.take() == Events({"on 2 61 100"}));
}

static void testGeneratedTimestampsAreValid() {
  // header 0b10xxxxxx and timestamp 0b1xxxxxxx as generated by MidiCommon
  RecordingAction action;
  MidiParser parser(&action);
  for (int hi = 0; hi < 64; hi += 7) {
    for (int lo = 0; lo < 128; lo += 13) {
      uint8_t msg[] = {(uint8_t)(0x80 | hi), (uint8_t)(0x80 | lo), 0x90, 60, 100};
      parser.parseBle(msg, sizeof(msg));
      Events ev = action.take();
      CHECK(ev == Events({"on 0 60 100"}));
    }
  }
}

int main() {
  MidiLogLevel = MidiError;  // suppress expected warnings
  testSingleMessage();
  testMultipleMessages();
  testRunningStatusWithTimestamp();
  testRunningStatusWithoutTimestamp();
  testRealtime();
  testPitchBend();
  testSysexOverMultiplePackets();
  testInvalidPacket();
  testShortPackets();
  testOneDataByteRunningStatus();
  testSysexInOnePacket();
  testRealtimeInsideRunningStatus();
  testTrailingTimestamp();
  testChannelFilter();
  testGeneratedTimestampsAreValid();
  return testResult("test_midi_ble_parser");
}
